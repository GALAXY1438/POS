BEGIN;

-- ── Helper: auto-update updated_at ──────────────────────────────────────────
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ── stores ──────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS stores (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_name        varchar(150) NOT NULL,
    name              varchar(150),                       -- legacy alias used by some pages
    branch            varchar(100),
    address           text,
    phone             varchar(30),
    email             varchar(100),
    currency_symbol   varchar(10) DEFAULT '$',
    tax_rate          decimal(5,2) DEFAULT 0.00,
    description       text,
    status            varchar(20) DEFAULT 'active',
    owner_id          integer NOT NULL,
    business_type     varchar(100) DEFAULT 'Retail',
    created_by        integer,
    created_at        timestamp DEFAULT CURRENT_TIMESTAMP,
    updated_at        timestamp DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE FUNCTION stores_sync_name() RETURNS trigger AS $$
BEGIN
    IF NEW.name IS NULL OR NEW.name = '' THEN NEW.name := NEW.store_name; END IF;
    IF NEW.store_name IS NULL OR NEW.store_name = '' THEN NEW.store_name := NEW.name; END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_stores_sync ON stores;
CREATE TRIGGER trg_stores_sync BEFORE INSERT OR UPDATE ON stores
    FOR EACH ROW EXECUTE FUNCTION stores_sync_name();

DROP TRIGGER IF EXISTS trg_stores_updated ON stores;
CREATE TRIGGER trg_stores_updated BEFORE UPDATE ON stores
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE INDEX IF NOT EXISTS idx_stores_status ON stores(status);

-- ── users ───────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS users (
    id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username                 varchar(50) NOT NULL UNIQUE,
    email                    varchar(100) UNIQUE,       -- nullable: POS customer accounts have no email
    password                 varchar(255) NOT NULL,
    role                     varchar(20) NOT NULL DEFAULT 'staff'
                             CHECK (role IN ('super_admin','admin','staff','cashier','customer')),
    store_id                 integer REFERENCES stores(id) ON DELETE SET NULL,
    first_name               varchar(50) NOT NULL DEFAULT '',
    last_name                varchar(50) NOT NULL DEFAULT '',
    business_type            varchar(50),
    status                   varchar(20) DEFAULT 'active',
    created_at               timestamp DEFAULT CURRENT_TIMESTAMP,
    updated_at               timestamp DEFAULT CURRENT_TIMESTAMP,
    email_verified           smallint DEFAULT 0,
    verification_otp         varchar(6),
    verification_otp_expires timestamp
);
CREATE INDEX IF NOT EXISTS idx_users_store ON users(store_id);

DROP TRIGGER IF EXISTS trg_users_updated ON users;
CREATE TRIGGER trg_users_updated BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ── categories ──────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS categories (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(100) NOT NULL,
    description text,
    store_id    integer,
    status      varchar(20) DEFAULT 'active',
    created_at  timestamp DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_categories_store ON categories(store_id);

-- ── products ────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS products (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                varchar(100) NOT NULL,
    sku                 varchar(64),
    category_id         integer REFERENCES categories(id),
    brand               varchar(100),
    price               decimal(10,2) NOT NULL,
    stock_quantity      integer DEFAULT 0,
    low_stock_threshold integer DEFAULT 10,
    barcode             varchar(100),
    expiry              date,
    description         text,
    image               varchar(255),
    status              varchar(20) DEFAULT 'active',
    store_id            integer REFERENCES stores(id) ON DELETE CASCADE,
    created_at          timestamp DEFAULT CURRENT_TIMESTAMP,
    updated_at          timestamp DEFAULT CURRENT_TIMESTAMP,
    last_updated_by     integer REFERENCES users(id) ON DELETE SET NULL,
    buying_price        decimal(10,2) DEFAULT 0.00,
    discount            decimal(5,2) DEFAULT 0.00,
    unit                varchar(30) DEFAULT 'pcs',
    manufacture_date    date,
    supplier_name       varchar(150),
    supplier_contact    varchar(100),
    purchase_date       date
);
CREATE INDEX IF NOT EXISTS idx_products_category ON products(category_id);
CREATE INDEX IF NOT EXISTS idx_products_store ON products(store_id);

DROP TRIGGER IF EXISTS trg_products_updated ON products;
CREATE TRIGGER trg_products_updated BEFORE UPDATE ON products
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ── inventory_reports ───────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS inventory_reports (
