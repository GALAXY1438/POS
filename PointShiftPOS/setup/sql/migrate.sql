-- ============================================================================
-- TechShift POS — schema updates
-- Safe to run on every start and after restoring an older backup.
-- Only idempotent statements belong here.
-- ============================================================================

-- Brands sit under a category (e.g. Maize Flour -> Soko, Raha, Maruti).
ALTER TABLE products ADD COLUMN IF NOT EXISTS brand varchar(100);

-- In-app notifications (low stock, expiry and system alerts).
CREATE TABLE IF NOT EXISTS notifications (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id    integer,
    type        varchar(30) NOT NULL DEFAULT 'system',
    severity    varchar(20) NOT NULL DEFAULT 'info',
    title       varchar(160) NOT NULL,
    message     text NOT NULL,
    link        varchar(255),
    dedup_key   varchar(120) UNIQUE,
    product_id  integer,
    is_read     smallint NOT NULL DEFAULT 0,
    sms_status  varchar(20) NOT NULL DEFAULT 'none',
    sms_error   varchar(255),
    created_at  timestamp DEFAULT CURRENT_TIMESTAMP,
    updated_at  timestamp DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_notifications_store ON notifications(store_id);
CREATE INDEX IF NOT EXISTS idx_notifications_read ON notifications(is_read);
CREATE INDEX IF NOT EXISTS idx_notifications_created ON notifications(created_at);

DROP TRIGGER IF EXISTS trg_notifications_updated ON notifications;
CREATE TRIGGER trg_notifications_updated BEFORE UPDATE ON notifications
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Support tickets raised from the in-app assistant.
CREATE TABLE IF NOT EXISTS support_tickets (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_ref  varchar(30) NOT NULL UNIQUE,
    user_id     integer,
    name        varchar(120),
    email       varchar(160) NOT NULL,
    role        varchar(30),
    store_id    integer,
    subject     varchar(180) NOT NULL,
    message     text NOT NULL,
    status      varchar(20) NOT NULL DEFAULT 'open',
    email_sent  smallint NOT NULL DEFAULT 0,
    created_at  timestamp DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_support_tickets_created ON support_tickets(created_at);

-- Per-user security preferences (two-factor authentication).
CREATE TABLE IF NOT EXISTS user_security (
    user_id       integer PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    twofa_enabled smallint NOT NULL DEFAULT 0,
    twofa_method  varchar(10) NOT NULL DEFAULT 'email',
    twofa_phone   varchar(30),
    updated_at    timestamp DEFAULT CURRENT_TIMESTAMP
);

-- System-wide audit trail.
CREATE TABLE IF NOT EXISTS audit_logs (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id     integer,
    username    varchar(100),
    role        varchar(30),
    store_id    integer,
    category    varchar(40) NOT NULL DEFAULT 'general',
    action      varchar(60) NOT NULL,
    description text,
    ip          varchar(60),
    user_agent  varchar(255),
    meta        text
);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created ON audit_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_user    ON audit_logs(user_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_action  ON audit_logs(action);
CREATE INDEX IF NOT EXISTS idx_audit_logs_category ON audit_logs(category);

-- Cash-drawer shift sessions (open/close with float and cash count).
CREATE TABLE IF NOT EXISTS register_shifts (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        integer NOT NULL,
    store_id       integer,
    opened_at      timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at      timestamp,
    opening_float  numeric(12,2) NOT NULL DEFAULT 0,
    closing_count  numeric(12,2),
    expected_cash  numeric(12,2),
    cash_sales     numeric(12,2) NOT NULL DEFAULT 0,
    mpesa_sales    numeric(12,2) NOT NULL DEFAULT 0,
    card_sales     numeric(12,2) NOT NULL DEFAULT 0,
    other_sales    numeric(12,2) NOT NULL DEFAULT 0,
    total_sales    numeric(12,2) NOT NULL DEFAULT 0,
    orders_count   integer NOT NULL DEFAULT 0,
    status         varchar(12) NOT NULL DEFAULT 'open',
    notes          text
);
CREATE INDEX IF NOT EXISTS idx_register_shifts_user   ON register_shifts(user_id, status);
CREATE INDEX IF NOT EXISTS idx_register_shifts_store  ON register_shifts(store_id, status);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS register_shift_id integer;
CREATE INDEX IF NOT EXISTS idx_orders_register_shift ON orders(register_shift_id);

-- Badge / barcode codes for scanner sign-in on the login screen.
ALTER TABLE users ADD COLUMN IF NOT EXISTS badge_code varchar(100);
CREATE UNIQUE INDEX IF NOT EXISTS uniq_users_badge_code
    ON users (badge_code) WHERE badge_code IS NOT NULL AND badge_code <> '';
