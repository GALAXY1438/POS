-- Brands sit under a category (e.g. Maize Flour -> Soko, Raha, Maruti).
ALTER TABLE products ADD COLUMN IF NOT EXISTS brand varchar(100);

-- In-app notifications (low stock, expiry and system alerts).
CREATE TABLE IF NOT EXISTS notifications (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id    integer,
    type        varchar(30) NOT NULL DEFAULT 'system',
    severity    varchar(20) NOT NULL DEFAULT 'info',
    title       varchar(160) NOT NULL,
    message     text NOT NULL,
    link        varchar(255),
    dedup_key   varchar(120) UNIQUE,
    product_id  integer,
    is_read     smallint NOT NULL DEFAULT 0,
    sms_status  varchar(20) NOT NULL DEFAULT 'none',
    sms_error   varchar(255),
    created_at  timestamp DEFAULT CURRENT_TIMESTAMP,
    updated_at  timestamp DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_notifications_store ON notifications(store_id);
CREATE INDEX IF NOT EXISTS idx_notifications_read ON notifications(is_read);
CREATE INDEX IF NOT EXISTS idx_notifications_created ON notifications(created_at);

DROP TRIGGER IF EXISTS trg_notifications_updated ON notifications;
CREATE TRIGGER trg_notifications_updated BEFORE UPDATE ON notifications
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
